"""Pydantic DTOs. These mirror frontend/src/domain/types.ts and viewport/types.ts one-to-one.
Field names are camelCase on the wire. Fields marked ADDITIVE do not exist in the frontend types
yet and are safe for it to ignore."""

from __future__ import annotations

from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field
from pydantic.alias_generators import to_camel


class DTO(BaseModel):
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True, extra="ignore")


Id = str

UniverseStatus = Literal["running", "paused", "initialising", "terminated", "archived"]
AgentStatus = Literal["active", "dormant", "deceased"]
CivilizationStage = Literal["none", "bands", "settlements", "polities", "industrial", "reflective"]
HypothesisState = Literal["proposed", "testing", "supported", "refuted", "withdrawn"]
ExperimentStatus = Literal["draft", "queued", "running", "complete", "aborted"]
EventSeverity = Literal["info", "notice", "warning", "critical"]
EventCategory = Literal["population", "civilization", "universe", "agent", "research", "system"]
KnowledgeSource = Literal["observation", "inference", "taught", "inherited"]
MemoryKind = Literal["perception", "action", "social", "reflection"]
RelationshipKind = Literal["parent", "offspring", "partner", "ally", "rival", "mentor", "student"]
EvidenceKind = Literal["observation", "measurement", "experiment", "testimony", "derivation"]
ExecutionMode = Literal["realtime", "lockstep"]
ProvenanceClass = Literal["prompt-exposed", "evidence-linked", "model-originated", "operator"]


# ---------------------------------------------------------------- universe


class SimulationClock(DTO):
    tick: int
    rate: float
    speed: float
    observed_at: str


class CreatedBy(DTO):
    kind: Literal["operator", "agent", "experiment"]
    id: Id | None
    label: str


class UniverseLineage(DTO):
    parent_id: Id | None
    depth: int
    created_by: CreatedBy
    created_at_tick: int
    created_at: str


class WorldField(DTO):
    key: str
    label: str
    value: float
    unit: str | None = None


class WorldConditions(DTO):
    width: int
    height: int
    seed: str
    fields: list[WorldField]


class PopulationStats(DTO):
    total: int
    alive: int
    born: int
    died: int
    mean_energy: float
    mean_age: float
    generations: int


class Universe(DTO):
    id: Id
    name: str
    code: str
    status: UniverseStatus
    clock: SimulationClock
    lineage: UniverseLineage
    population: PopulationStats
    world: WorldConditions
    civilization_stage: CivilizationStage | None
    child_ids: list[Id]
    # ADDITIVE
    mode: ExecutionMode = "realtime"
    cell_size: int = 8
    model_ref: str | None = None
    compute_share: float = 1.0
    config_version: int = 1
    engine_version: str = ""


# ---------------------------------------------------------------- agents


class AgentRelationship(DTO):
    agent_id: Id
    kind: RelationshipKind
    affinity: float
    since_tick: int


class KnowledgeItem(DTO):
    id: Id
    topic: str
    confidence: float
    acquired_at_tick: int
    source: KnowledgeSource
    # ADDITIVE
    statement: str | None = None


class MemoryRecord(DTO):
    id: Id
    tick: int
    kind: MemoryKind
    summary: str
    salience: float
    # ADDITIVE: whether the record was generated by mechanics or asserted by a model
    source: KnowledgeSource = "observation"


class Position(DTO):
    x: float
    y: float


class AgentLineage(DTO):
    parent_ids: list[Id]
    offspring_ids: list[Id]


class Trait(DTO):
    key: str
    label: str
    value: float


class Agent(DTO):
    id: Id
    universe_id: Id
    name: str
    status: AgentStatus
    generation: int
    born_at_tick: int
    died_at_tick: int | None
    age: int
    energy: float
    position: Position
    lineage: AgentLineage
    relationships: list[AgentRelationship]
    knowledge: list[KnowledgeItem]
    memory: list[MemoryRecord]
    traits: list[Trait]
    # ADDITIVE
    inventory: dict[str, float] = Field(default_factory=dict)
    intent: dict[str, Any] | None = None
    policy: Literal["reflex", "model"] = "reflex"
    model_ref: str | None = None
    decisions_total: int = 0
    decisions_model: int = 0


# ---------------------------------------------------------------- civilization


class PopulationEra(DTO):
    id: Id
    label: str
    from_tick: int
    to_tick: int | None
    peak_population: int
    note: str | None = None


class Technology(DTO):
    id: Id
    name: str
    tier: int
    state: Literal["unknown", "emerging", "established"]
    requires: list[Id]
    discovered_at_tick: int | None
    discovered_by: Id | None
    # ADDITIVE
    progress: float = 0.0


class Institution(DTO):
    id: Id
    name: str
    kind: Literal["kinship", "council", "guild", "market", "cult", "academy", "state"]
    members: int
    founded_at_tick: int


class Infrastructure(DTO):
    id: Id
    name: str
    count: int
    condition: float


class CollectiveKnowledge(DTO):
    id: Id
    topic: str
    holders: int
    confidence: float


class Civilization(DTO):
    universe_id: Id
    stage: CivilizationStage
    eras: list[PopulationEra]
    technologies: list[Technology]
    institutions: list[Institution]
    infrastructure: list[Infrastructure]
    collective_knowledge: list[CollectiveKnowledge]


# ---------------------------------------------------------------- research


class Evidence(DTO):
    id: Id
    kind: EvidenceKind
    source: str
    weight: float
    tick: int
    summary: str
    # ADDITIVE
    verified_by_mechanics: bool = False


class Actor(DTO):
    kind: Literal["agent", "operator", "system"]
    id: Id | None
    label: str


class ReasoningStep(DTO):
    id: Id
    index: int
    tick: int
    actor: Actor
    statement: str
    confidence: float


class ProposedBy(DTO):
    kind: Literal["agent", "operator"]
    id: Id | None
    label: str


class Provenance(DTO):
    """ADDITIVE: how a hypothesis came to exist, with the caveats that apply."""

    classification: ProvenanceClass
    prompt_exposed_terms: list[str]
    verified_evidence_ratio: float
    note: str


class Hypothesis(DTO):
    id: Id
    universe_id: Id
    title: str
    statement: str
    state: HypothesisState
    confidence: float
    proposed_at_tick: int
    proposed_by: ProposedBy
    evidence: list[Evidence]
    reasoning: list[ReasoningStep]
    experiment_ids: list[Id]
    # ADDITIVE
    provenance: Provenance | None = None
    existential: bool = False


# ---------------------------------------------------------------- experiments


class ExperimentVariable(DTO):
    key: str
    label: str
    control: str | float | int | bool
    treatment: str | float | int | bool
    unit: str | None = None


class ExperimentRun(DTO):
    id: Id
    index: int
    started_at: str
    finished_at: str | None
    seed: str
    status: ExperimentStatus
    universe_ids: list[Id]
    # ADDITIVE
    control_universe_id: Id | None = None
    treatment_universe_id: Id | None = None
    metrics: dict[str, Any] | None = None


class Reproducibility(DTO):
    seed: str
    engine_version: str | None
    snapshot_hash: str | None
    deterministic: bool


class Experiment(DTO):
    id: Id
    name: str
    objective: str
    status: ExperimentStatus
    control_universe_id: Id | None
    variables: list[ExperimentVariable]
    replicates: int
    reproducibility: Reproducibility
    runs: list[ExperimentRun]
    hypothesis_ids: list[Id]
    created_at: str
    # ADDITIVE
    duration_ticks: int = 2_000
    mode: ExecutionMode = "lockstep"
    base_config: dict[str, Any] = Field(default_factory=dict)


# ---------------------------------------------------------------- events


class EventRef(DTO):
    kind: Literal["agent", "universe", "hypothesis", "experiment"]
    id: Id


class WorldEvent(DTO):
    id: Id
    universe_id: Id
    tick: int
    severity: EventSeverity
    category: EventCategory
    summary: str
    refs: list[EventRef] | None = None


# ---------------------------------------------------------------- settings


class ProviderConfig(DTO):
    id: Id
    label: str
    adapter: str
    base_url: str
    model: str
    has_credential: bool
    enabled: bool


class ReasoningConfig(DTO):
    provider_id: Id | None
    temperature: float
    max_steps: int
    memory_window: int
    reflection_interval: int
    # ADDITIVE
    decision_interval: int = 120
    num_ctx: int = 4096
    think_decisions: bool = False
    think_reflection: bool = True
    prompt_profile: str = "neutral"
    concurrency: int = 1
    timeout_s: float = 120.0


class SimulationParams(DTO):
    tick_rate: int
    world_width: int
    world_height: int
    initial_population: int
    mutation_rate: float
    energy_decay: float
    # ADDITIVE
    cell_size: int = 8


class PerformanceConfig(DTO):
    render_scale: float
    entity_cap: int
    fps_cap: int
    cull_offscreen: bool


class PersistenceConfig(DTO):
    snapshot_interval_ticks: int
    retain_snapshots: int
    autosave: bool
    store_path: str


class OperatorSettings(DTO):
    providers: list[ProviderConfig]
    reasoning: ReasoningConfig
    simulation: SimulationParams
    performance: PerformanceConfig
    persistence: PersistenceConfig


# ---------------------------------------------------------------- viewport snapshot


TerrainClass = Literal["void", "barren", "fertile", "water", "built"]
EntityKind = Literal["agent", "structure", "resource", "portal"]


class TerrainCell(DTO):
    x: int
    y: int
    cls: TerrainClass
    v: float


class EntityMarker(DTO):
    id: str
    kind: EntityKind
    x: float
    y: float
    level: float
    faded: bool | None = None
    label: str | None = None


class WorldSnapshot(DTO):
    universe_id: str
    tick: int
    width: int
    height: int
    cell_size: int
    terrain: list[TerrainCell]
    entities: list[EntityMarker]


# ---------------------------------------------------------------- commands / writes


class CommandResult(DTO):
    accepted: bool
    reason: str | None = None


class CreateUniverseRequest(DTO):
    name: str | None = None
    seed: str | None = None
    config: dict[str, Any] = Field(default_factory=dict)
    initial_population: int | None = None
    mode: ExecutionMode = "realtime"
    start: bool = True


class CreateExperimentRequest(DTO):
    name: str
    objective: str = ""
    variables: list[ExperimentVariable] = Field(default_factory=list)
    replicates: int = 1
    seed: str | None = None
    duration_ticks: int = 2_000
    mode: ExecutionMode = "lockstep"
    hypothesis_ids: list[Id] = Field(default_factory=list)
    base_config: dict[str, Any] = Field(default_factory=dict)
    control_universe_id: Id | None = None


class PatchExperimentRequest(DTO):
    name: str | None = None
    objective: str | None = None
    variables: list[ExperimentVariable] | None = None
    replicates: int | None = None
    seed: str | None = None
    duration_ticks: int | None = None
    mode: ExecutionMode | None = None
    hypothesis_ids: list[Id] | None = None
    status: ExperimentStatus | None = None


class CreateHypothesisRequest(DTO):
    universe_id: Id
    title: str
    statement: str
    confidence: float = 0.5
    experiment_ids: list[Id] = Field(default_factory=list)


class CredentialRequest(DTO):
    credential: str | None


